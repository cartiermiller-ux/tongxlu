import Foundation

/// 短信采集 —— **iOS 上物理不可能实现**
///
/// ## 为什么这里是个空实现
///
/// 安卓端 `AnyCollectorSms.kt` 能工作，是因为安卓提供了 `READ_SMS` 运行时权限 +
/// `Telephony.Sms` / `content://sms` 内容提供器。**iOS 完全没有对应能力**：
///
/// 1. **没有权限项**：iOS 的隐私权限清单里**不存在**任何"读取短信"的项
///    （通讯录/相册/定位/麦克风/相机/提醒事项…有，短信没有）
/// 2. **沙盒隔离**：短信数据库 `sms.db` 位于系统私有容器，第三方 App 无权访问
/// 3. **无公开 API**：`MessageUI` 框架只能**发送**短信（`MFMessageComposeViewController`），
///    **不能读取**收件箱
/// 4. **越狱设备除外**：只有越狱后才能读，但越狱设备无法通过正规签名分发
///
/// 所以这不是"还没做"，而是**平台层面做不到**。
///
/// ## 对上报协议的影响
///
/// 服务端 `/api/uploads/apisms` 要求：
/// - 首元素是身份头 `{"imei":手机号,"imei2":邀请码}`
/// - 其后每条短信一个对象，**数组长度必须 ≥ 2**
///
/// 短信数为 0 时数组长度 < 2，服务端返回「获取信息错误」。
/// 因此本端**直接跳过调用**（与安卓端"短信为空则跳过"的策略一致），
/// 注册报文中 `clientid` 的短信数位置**固定填 0**。
///
/// ## 交付说明
///
/// 这一条是 iOS 与安卓**功能无法对齐**的唯一一处硬缺口，已在
/// `docs/功能对齐说明.md` 中向用户明示。
enum AnyCollectorSms {

    /// 永远返回空数组 —— iOS 无法读取短信
    static func fetchAll() async -> [AnySmsPayload] {
        AnyLog.i("短信采集：iOS 平台不支持读取短信，跳过（详见 AnyCollectorSms 注释）")
        return []
    }

    /// 短信条数（注册报文用）—— 恒为 0
    static var count: Int { 0 }
}
